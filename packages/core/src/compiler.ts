import type { AdlDocument } from "@axiom/adl";

export type CompileTarget = "generic" | "claude" | "antigravity" | "codex" | "cursor";

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface CompileResult {
  target: CompileTarget;
  files: GeneratedFile[];
  warnings: string[];
}

function renderSkills(doc: AdlDocument): string {
  const inc = doc.skills?.include ?? [];
  return inc.length ? inc.map((s) => `- ${s}`).join("\n") : "- (none declared)";
}

function renderPolicies(doc: AdlDocument): string {
  const p = doc.policies ?? {};
  const lines: string[] = [];
  for (const [group, vals] of Object.entries(p)) {
    if (!vals || typeof vals !== "object") continue;
    lines.push(`### ${group}`);
    for (const [k, v] of Object.entries(vals as Record<string, unknown>)) {
      lines.push(`- ${k}: ${v}`);
    }
  }
  return lines.length ? lines.join("\n") : "(none)";
}

function identityLine(doc: AdlDocument): string {
  const a = doc.agent;
  const role = a?.identity?.role ?? a?.name ?? "Axiom Agent";
  return role;
}

function buildInstructions(doc: AdlDocument): string {
  const project = doc.project?.name ?? "project";
  const role = identityLine(doc);
  const responsibilities = doc.agent?.identity?.responsibilities ?? [];
  const objectives = doc.agent?.identity?.objectives ?? [];
  const constraints = doc.capabilities?.constraints ?? [];

  return [
    `# Axiom Agent Configuration`,
    ``,
    `Project: ${project}`,
    `Role: ${role}`,
    ``,
    `## Responsibilities`,
    responsibilities.length ? responsibilities.map((r) => `- ${r}`).join("\n") : "- (none)",
    ``,
    `## Objectives`,
    objectives.length ? objectives.map((o) => `- ${o}`).join("\n") : "- (none)",
    ``,
    `## Capabilities`,
    `Required: ${(doc.capabilities?.required ?? []).join(", ") || "(none)"}`,
    `Optional: ${(doc.capabilities?.optional ?? []).join(", ") || "(none)"}`,
    ``,
    `## Constraints`,
    constraints.length ? constraints.map((c) => `- ${c}`).join("\n") : "- (none)",
    ``,
    `## Skills`,
    renderSkills(doc),
    ``,
    `## Presets`,
    (doc.presets?.active ?? []).map((p) => `- ${p}`).join("\n") || "- (none)",
    ``,
    `## Workflows`,
    (doc.workflows?.active ?? []).map((w) => `- ${w}`).join("\n") || "- (none)",
    ``,
    `## Policies`,
    renderPolicies(doc),
    ``,
    `## Tools`,
    `Filesystem: ${doc.tools?.filesystem?.enabled ? "enabled" : "disabled"}`,
    `Terminal: ${doc.tools?.terminal?.enabled ? "enabled" : "disabled"}`,
    `Git: ${doc.tools?.git?.enabled ? "enabled" : "disabled"}`,
    `MCP: ${doc.tools?.mcp?.enabled ? "enabled" : "disabled"}`,
    ``,
    `## Verification`,
    `Required: ${(doc.verification?.required ?? []).join(", ") || "(none)"}`,
    `Require verified results: ${doc.verification?.completion?.require_verified_results ?? false}`,
    ``,
    `> Generated by Axiom. Canonical source: axiom.yaml / .axiom/. Do not edit generated files; sync via \`axiom agent sync\`.`,
  ].join("\n");
}

export function compile(doc: AdlDocument, target: CompileTarget): CompileResult {
  const warnings: string[] = [];
  const files: GeneratedFile[] = [];

  if (target === "generic") {
    files.push({ path: ".axiom/generated/generic/config.json", content: JSON.stringify(doc, null, 2) + "\n" });
    return { target, files, warnings };
  }

  const instructions = buildInstructions(doc);

  if (target === "claude") {
    files.push({ path: "CLAUDE.md", content: instructions + "\n" });
    files.push({ path: ".axiom/generated/claude/config.json", content: JSON.stringify(doc, null, 2) + "\n" });
  } else if (target === "antigravity") {
    files.push({ path: "AGENTS.md", content: instructions + "\n" });
    files.push({ path: ".axiom/generated/antigravity/config.json", content: JSON.stringify(doc, null, 2) + "\n" });
  } else if (target === "codex") {
    files.push({ path: "AGENTS.md", content: instructions + "\n" });
    files.push({ path: ".axiom/generated/codex/config.json", content: JSON.stringify(doc, null, 2) + "\n" });
  } else if (target === "cursor") {
    files.push({ path: ".cursor/rules/axiom.mdc", content: `---\ndescription: Axiom agent configuration\nglobs: \nalwaysApply: true\n---\n\n${instructions}\n` });
    files.push({ path: ".axiom/generated/cursor/config.json", content: JSON.stringify(doc, null, 2) + "\n" });
  }

  // warn about unsupported features per target (basic)
  const matrix: Record<CompileTarget, string[]> = {
    generic: [],
    claude: ["mcp servers declared are passed through; ensure Claude Code supports them"],
    antigravity: [],
    codex: [],
    cursor: ["cursor rules are single-file; complex workflows may be truncated"],
  };
  for (const w of matrix[target]) warnings.push(w);

  return { target, files, warnings };
}